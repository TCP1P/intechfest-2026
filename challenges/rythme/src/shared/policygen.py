#!/usr/bin/env python3
"""Generate the release-coupled Rythme v6 policy constants.

Change RELEASE_SEED for a new issued client/server pair, run with --write, and
commit all three outputs. Normal builds use --check to reject cross-language
drift. This file is author material and is not included in the player handout.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


RELEASE_SEED = b"rythme-v6|osu-0f3d3c3|intechfest-2026|stateful-frame-v1"
ROOT = Path(__file__).resolve().parents[2]
OUTPUTS = {
    ROOT / "src/server/internal/arena/policy_generated.go": "go",
    ROOT / "src/client/Rythme.Desktop/NativePolicyIds.cs": "csharp",
    ROOT / "src/client/native/rythme-native/src/generated.rs": "rust",
}

OPERATIONS = (
    ("ABI", "Abi"),
    ("INITIALIZE", "Initialize"),
    ("HEALTH", "Health"),
    ("OPEN_CHANNEL", "OpenChannel"),
    ("CREATE_REQUEST", "CreateRequest"),
    ("VERIFY_RESPONSE", "VerifyResponse"),
    ("VERIFY_HANDSHAKE", "VerifyHandshake"),
    ("BUILD_ENVELOPE", "BuildEnvelope"),
    ("FINALIZE", "Finalize"),
    ("CLOSE", "Close"),
)


def derive(label: str, length: int) -> bytes:
    return hashlib.shake_256(RELEASE_SEED + b"\0" + label.encode("ascii")).digest(length)


def operation_ids() -> dict[str, int]:
    values = {
        rust: int.from_bytes(derive(f"dispatch:{rust}", 4), "little") | 0x01010101
        for rust, _ in OPERATIONS
    }
    if len(set(values.values())) != len(values) or 0 in values.values():
        raise RuntimeError("release seed produced colliding dispatcher identifiers")
    return values


def policy_bytes() -> tuple[int, tuple[int, int, int, int]]:
    chosen: list[int] = []
    for label in ("profile-tag", "select-index", "validate", "emit", "halt"):
        candidate = derive(f"vm:{label}", 1)[0]
        while candidate == 0 or candidate in chosen:
            candidate = (candidate + 1) & 0xFF
        chosen.append(candidate)
    return chosen[0], tuple(chosen[1:])  # type: ignore[return-value]


def frame_actions() -> dict[str, int]:
    labels = ("enroll", "ready", "cues", "input", "result", "finish")
    values: dict[str, int] = {}
    used: set[int] = set()
    for label in labels:
        candidate = 0x10 + derive(f"frame:{label}", 1)[0] % 0x60
        while candidate in used:
            candidate = 0x10 + ((candidate - 0x10 + 1) % 0x60)
        used.add(candidate)
        values[label] = candidate
    return values


def byte_lines(value: bytes, width: int, indent: str) -> str:
    return "\n".join(
        indent + ", ".join(f"0x{byte:02x}" for byte in value[offset : offset + width]) + ","
        for offset in range(0, len(value), width)
    )


def render_go() -> str:
    tag, (select, validate, emit, halt) = policy_bytes()
    capsule = derive("key:capsule", 32)
    proof = derive("key:proof", 32)
    variant = derive("key:variant", 32)
    frame_magic = derive("frame:magic", 4)
    actions = frame_actions()
    return f'''// Code generated by src/shared/policygen.py from the Rythme v6 release seed.
// DO NOT EDIT.

package arena

const (
\tpolicyProfileTag byte = 0x{tag:02x}
\tvmSelectIndex    byte = 0x{select:02x}
\tvmValidate       byte = 0x{validate:02x}
\tvmEmit           byte = 0x{emit:02x}
\tvmHalt           byte = 0x{halt:02x}
\tframeEnroll      byte = 0x{actions['enroll']:02x}
\tframeReady       byte = 0x{actions['ready']:02x}
\tframeCues        byte = 0x{actions['cues']:02x}
\tframeInput       byte = 0x{actions['input']:02x}
\tframeResult      byte = 0x{actions['result']:02x}
\tframeFinish      byte = 0x{actions['finish']:02x}
)

var frameMagic = [4]byte{{
{byte_lines(frame_magic, 4, chr(9))}
}}

var policyCapsuleKey = [32]byte{{
{byte_lines(capsule, 8, chr(9))}
}}

var policyProofKey = [32]byte{{
{byte_lines(proof, 8, chr(9))}
}}

var policyVariantKey = [32]byte{{
{byte_lines(variant, 8, chr(9))}
}}
'''


def render_csharp() -> str:
    ids = operation_ids()
    actions = frame_actions()
    frame_magic = derive("frame:magic", 4)
    constants = "\n".join(
        f"    public const uint {csharp} = 0x{ids[rust]:08x};" for rust, csharp in OPERATIONS
    )
    action_constants = "\n".join(
        f"    public const byte Frame{label.title()} = 0x{value:02x};"
        for label, value in actions.items()
    )
    magic = ", ".join(f"0x{value:02x}" for value in frame_magic)
    return f'''// Code generated by src/shared/policygen.py from the Rythme v6 release seed.
// DO NOT EDIT.

namespace Rythme.Desktop;

internal static class NativePolicyIds
{{
{constants}
{action_constants}
    public static ReadOnlySpan<byte> FrameMagic => [{magic}];
}}
'''


def rust_u32(value: int) -> str:
    raw = f"{value:08x}"
    return raw[:4] + "_" + raw[4:]


def render_rust() -> str:
    ids = operation_ids()
    tag, (select, validate, emit, halt) = policy_bytes()
    capsule = derive("key:capsule", 32)
    proof = derive("key:proof", 32)
    variant = derive("key:variant", 32)
    capsule_mask = derive("mask:capsule", 32)
    proof_mask = derive("mask:proof", 32)
    variant_mask = derive("mask:variant", 32)
    capsule_share = bytes(left ^ right for left, right in zip(capsule, capsule_mask))
    proof_share = bytes(left ^ right for left, right in zip(proof, proof_mask))
    variant_share = bytes(left ^ right for left, right in zip(variant, variant_mask))
    frame_magic = derive("frame:magic", 4)
    actions = frame_actions()
    operations = "\n".join(
        f"pub const OP_{rust}: u32 = 0x{rust_u32(ids[rust])};" for rust, _ in OPERATIONS
    )
    action_constants = "\n".join(
        f"pub const FRAME_{label.upper()}: u8 = 0x{value:02x};" for label, value in actions.items()
    )
    return f'''// Code generated by src/shared/policygen.py from the Rythme v6 release seed.
// DO NOT EDIT.

{operations}

pub const PROFILE_TAG: u8 = 0x{tag:02x};
pub const VM_SELECT_INDEX: u8 = 0x{select:02x};
pub const VM_VALIDATE: u8 = 0x{validate:02x};
pub const VM_EMIT: u8 = 0x{emit:02x};
pub const VM_HALT: u8 = 0x{halt:02x};
pub const FRAME_MAGIC: [u8; 4] = [{', '.join(f'0x{value:02x}' for value in frame_magic)}];
{action_constants}

const CAPSULE_MASK: [u8; 32] = [
{byte_lines(capsule_mask, 16, "    ")}
];
const CAPSULE_SHARE: [u8; 32] = [
{byte_lines(capsule_share, 16, "    ")}
];
const PROOF_MASK: [u8; 32] = [
{byte_lines(proof_mask, 16, "    ")}
];
const PROOF_SHARE: [u8; 32] = [
{byte_lines(proof_share, 16, "    ")}
];
const VARIANT_MASK: [u8; 32] = [
{byte_lines(variant_mask, 16, "    ")}
];
const VARIANT_SHARE: [u8; 32] = [
{byte_lines(variant_share, 16, "    ")}
];

#[inline(never)]
fn unfold(mask: &[u8; 32], share: &[u8; 32]) -> [u8; 32] {{
    let mut result = [0u8; 32];
    for (index, output) in result.iter_mut().enumerate() {{
        // Volatile reads keep the two release-derived shares separate in the
        // optimized image. They remain recoverable by a determined reverser.
        let left = unsafe {{ std::ptr::read_volatile(mask.as_ptr().add(index)) }};
        let right = unsafe {{ std::ptr::read_volatile(share.as_ptr().add(index)) }};
        *output = left ^ right;
    }}
    result
}}

pub fn capsule_key() -> [u8; 32] {{
    unfold(&CAPSULE_MASK, &CAPSULE_SHARE)
}}

pub fn proof_key() -> [u8; 32] {{
    unfold(&PROOF_MASK, &PROOF_SHARE)
}}

pub fn variant_key() -> [u8; 32] {{
    unfold(&VARIANT_MASK, &VARIANT_SHARE)
}}
'''


def rendered(kind: str) -> str:
    return {"go": render_go, "csharp": render_csharp, "rust": render_rust}[kind]()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="replace generated outputs")
    parser.add_argument("--check", action="store_true", help="verify generated outputs (default)")
    parser.add_argument(
        "--check-native-image",
        type=Path,
        metavar="DLL",
        help="also reject a native image containing an unfolded release key",
    )
    args = parser.parse_args()
    if args.write and args.check:
        parser.error("choose either --write or --check")

    stale: list[Path] = []
    for path, kind in OUTPUTS.items():
        expected = rendered(kind)
        if args.write:
            path.write_text(expected, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
        elif not path.exists() or path.read_text(encoding="utf-8") != expected:
            stale.append(path)

    if stale:
        for path in stale:
            print(f"stale generated policy: {path.relative_to(ROOT)}")
        print("run: python3 src/shared/policygen.py --write")
        return 1
    if args.check_native_image is not None:
        image = args.check_native_image.read_bytes()
        exposed = [
            name
            for name, secret in (
                ("capsule", derive("key:capsule", 32)),
                ("proof", derive("key:proof", 32)),
                ("variant", derive("key:variant", 32)),
            )
            if secret in image
        ]
        if exposed:
            print(
                "native image contains unfolded release key(s): "
                + ", ".join(exposed)
            )
            return 1
        print("native image keeps capsule, proof, and variant keys split")
    if not args.write:
        print("generated policy constants are synchronized")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
