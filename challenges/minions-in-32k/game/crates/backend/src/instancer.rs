//! Game-instance provisioning.
//!
//! `LocalProcess` spawns server binaries on this host — the dev/test path and
//! the smallest production fallback. `K8sInstancer` creates `ChallengeInstance`
//! objects (`rctf-instancer.osec.io/v1`) in a cluster: one pod per lobby,
//! tagged with the match's `udprouter.es3n1n.io/instance-id` label so the
//! external UDP router can demux players to it. Instances are keyed
//! `challengeIntegrationId-teamId`, so we pass the match id as the synthetic
//! teamId.

use anyhow::{Context, Result};
use base64::Engine;
use serde_json::json;
use std::collections::VecDeque;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex};

pub struct InstanceRequest {
    pub match_id: String,
    /// (team_uuid, rCTF display name, access_key)
    pub players: Vec<(String, String, String)>,
    pub report_url: String,
    pub replay_upload_url: Option<String>,
    pub report_token: String,
    pub grace_secs: u64,
    pub match_secs: u64,
    pub arena: String,
    /// 32 hex chars (16 bytes) — the udp-router demux key. Generated by
    /// matchmaking, one per server. Unused by `LocalProcess`.
    pub instance_id: String,
    /// challengeIntegrationId — names the ChallengeInstance object.
    pub challenge_id: String,
    /// Per-match deterministic RNG seed. Passed to the server as `--seed` so
    /// the authoritative sim is reproducible and the replay records it.
    pub seed: u64,
    /// Forwarded k8s pod spec (`{ "pods": [...] }`); required by the K8s
    /// instancer, ignored by `LocalProcess`.
    pub config: Option<serde_json::Value>,
}

/// WebTransport bridge details — dev/local only. Production is native QUIC
/// through the udp-router, so the k8s path leaves this `None`.
pub struct WtInfo {
    pub port: u16,
    pub cert_hash_hex: String,
}

pub struct InstanceEndpoint {
    pub host: String,
    pub port: u16,
    /// SHA-256 of the DER cert the game server presents for native QUIC.
    pub cert_hash_hex: Option<String>,
    /// `true` → players route through the udp-router with the match
    /// instance-id (k8s/prod). `false` → they dial host:port directly (dev).
    pub routed: bool,
    pub wt: Option<WtInfo>,
}

/// Kubernetes names/namespace segments must be DNS-safe. The original rCTF
/// challenge id stays in backend state for score posts; only CRD/controller
/// fields are sanitized.
fn k8s_name_segment(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len().min(253));
    let mut last_was_dash = false;

    for c in raw.chars() {
        let c = c.to_ascii_lowercase();
        let mapped = if c.is_ascii_alphanumeric() || c == '-' {
            c
        } else {
            '-'
        };
        if mapped == '-' {
            if !last_was_dash {
                out.push(mapped);
            }
            last_was_dash = true;
        } else {
            out.push(mapped);
            last_was_dash = false;
        }
    }

    let mut name = out.trim_matches('-').to_string();
    if name.len() > 253 {
        name.truncate(253);
        name = name.trim_end_matches('-').to_string();
    }
    if name.is_empty() {
        "minions-instance".into()
    } else {
        name
    }
}

pub fn challenge_instance_name(challenge_id: &str, match_id: &str) -> String {
    k8s_name_segment(&format!("{challenge_id}-{match_id}"))
}

/// Per-player connection lines surfaced to teams as "server info".
pub fn build_connection(
    ep: &InstanceEndpoint,
    instance_id: &str,
    key: &str,
    public_base: &str,
) -> Vec<String> {
    let mut out = Vec::new();
    let cert_hash = ep
        .cert_hash_hex
        .as_deref()
        .or_else(|| ep.wt.as_ref().map(|wt| wt.cert_hash_hex.as_str()));
    let hash_arg = cert_hash
        .map(|h| format!(" --cert-hash {h}"))
        .unwrap_or_default();
    if ep.routed {
        out.push(format!(
            "client.exe --remote {}:{} --instance-id {} --key {}{}",
            ep.host, ep.port, instance_id, key, hash_arg
        ));
        out.push(format!(
            "client --remote {}:{} --instance-id {} --key {}{}",
            ep.host, ep.port, instance_id, key, hash_arg
        ));
    } else {
        // Pin the backend-minted server cert so a matchmade native client
        // verifies the exact cert, not just any self-signed one.
        out.push(format!(
            "client.exe --remote {}:{} --key {}{}",
            ep.host, ep.port, key, hash_arg
        ));
        out.push(format!(
            "client --remote {}:{} --key {}{}",
            ep.host, ep.port, key, hash_arg
        ));
    }
    if let Some(wt) = &ep.wt {
        // Key goes in the URL fragment (`#`), never the query string: fragments
        // aren't sent to servers, aren't logged in access logs, and aren't
        // forwarded in the Referer header. The client reads it from the
        // fragment. Non-secret params stay in the query for visibility.
        out.push(format!(
            "{}/wasm?host={}&port={}&certhash={}#key={}",
            public_base, ep.host, wt.port, wt.cert_hash_hex, key
        ));
    }
    out
}

/// Per-instance ECDSA P-256 cert, 13-day validity — within the browser
/// limit (≤14 days) for serverCertificateHashes pinning.
fn mint_wt_cert() -> Result<(String, String, String)> {
    use rcgen::{CertificateParams, DnType, KeyPair, PKCS_ECDSA_P256_SHA256};
    let key = KeyPair::generate_for(&PKCS_ECDSA_P256_SHA256)?;
    let mut params = CertificateParams::new(vec!["localhost".into()])?;
    params
        .distinguished_name
        .push(DnType::CommonName, "minions-instance");
    let now = std::time::SystemTime::now();
    params.not_before = now.into();
    params.not_after = (now + std::time::Duration::from_secs(13 * 24 * 3600)).into();
    let cert = params.self_signed(&key)?;
    let cert_der = cert.der().to_vec();
    let b64 = base64::engine::general_purpose::STANDARD;
    let hash = {
        use std::fmt::Write;
        // sha256 via ring (already in the tree through rustls)
        let digest = ring::digest::digest(&ring::digest::SHA256, &cert_der);
        digest.as_ref().iter().fold(String::new(), |mut s, b| {
            let _ = write!(s, "{b:02x}");
            s
        })
    };
    Ok((b64.encode(&cert_der), b64.encode(key.serialize_der()), hash))
}

#[allow(async_fn_in_trait)]
pub trait Instancer: Send + Sync {
    async fn create(&self, req: &InstanceRequest) -> Result<InstanceEndpoint>;
}

/// How many concurrent local instances we provision ports for. Each instance
/// uses a pair (game + WebTransport), so the pool reserves `LOCAL_PORT_SLOTS`
/// pairs starting at `base_port`.
const LOCAL_PORT_SLOTS: u16 = 64;

type PortPool = Arc<Mutex<VecDeque<(u16, u16)>>>;

pub struct LocalProcess {
    pub server_bin: PathBuf,
    pub public_host: String,
    /// Recycled pool of free (game, wt) port pairs. Bounded — exhaustion is an
    /// error, not a silent wraparound into a colliding/privileged port. Shared
    /// (Arc) so the per-instance reaper can return ports on exit.
    free_ports: PortPool,
    /// Where finalized replays are exported once the instance exits. `None` →
    /// no export (replay stays in the per-match temp dir). Spectators only ever
    /// read from this bucket, so a live match is never viewable.
    replay_bucket: Option<PathBuf>,
}

impl LocalProcess {
    pub fn new(
        server_bin: PathBuf,
        public_host: String,
        base_port: u16,
        replay_bucket: Option<PathBuf>,
    ) -> Self {
        let free_ports = (0..LOCAL_PORT_SLOTS)
            .filter_map(|i| {
                let game = base_port.checked_add(i.checked_mul(2)?)?;
                let wt = game.checked_add(1)?;
                Some((game, wt))
            })
            .collect();
        Self {
            server_bin,
            public_host,
            free_ports: Arc::new(Mutex::new(free_ports)),
            replay_bucket,
        }
    }

    fn acquire_ports(&self) -> Result<(u16, u16)> {
        crate::state::lock(&self.free_ports)
            .pop_front()
            .context("local instancer port pool exhausted (too many live instances)")
    }

    fn release_ports(&self, ports: (u16, u16)) {
        crate::state::lock(&self.free_ports).push_back(ports);
    }
}

/// Copy a finished match's replay out of its per-match temp dir into the
/// bucket as `<bucket>/<challenge_id>/<match_id>.mrpl`. Best-effort: a missing
/// replay or copy error is logged, not fatal. Only finished matches reach here
/// (the reaper calls this after a clean instance exit), so the bucket only ever
/// holds finalized replays — the spectator reads exclusively from it.
async fn export_replay(replay_dir: &Path, bucket: &Path, challenge_id: &str, match_id: &str) {
    let src = match find_replay(replay_dir).await {
        Some(p) => p,
        None => {
            tracing::warn!(dir = %replay_dir.display(), %match_id, "no replay file to export");
            return;
        }
    };
    let dest_dir = bucket.join(challenge_id);
    if let Err(e) = tokio::fs::create_dir_all(&dest_dir).await {
        tracing::warn!(error = %e, dir = %dest_dir.display(), "replay bucket mkdir failed");
        return;
    }
    let dest = dest_dir.join(format!("{match_id}.mrpl"));
    match tokio::fs::copy(&src, &dest).await {
        Ok(_) => tracing::info!(%match_id, dest = %dest.display(), "replay exported to bucket"),
        Err(e) => tracing::warn!(error = %e, src = %src.display(), "replay export copy failed"),
    }
}

/// First `*.mrpl` file in `dir`, if any.
async fn find_replay(dir: &Path) -> Option<PathBuf> {
    let mut entries = tokio::fs::read_dir(dir).await.ok()?;
    while let Ok(Some(entry)) = entries.next_entry().await {
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) == Some("mrpl") {
            return Some(path);
        }
    }
    None
}

/// `PLAYER_TOKENS` JSON the game server reads: `[{uuid,name,key}, ...]`.
/// Falls back to `[]` on the (unreachable) serialization error.
fn player_tokens_json(players: &[(String, String, String)]) -> String {
    serde_json::to_string(
        &players
            .iter()
            .map(|(u, n, k)| json!({"uuid": u, "name": n, "key": k}))
            .collect::<Vec<_>>(),
    )
    .unwrap_or_else(|_| "[]".to_string())
}

impl Instancer for LocalProcess {
    async fn create(&self, req: &InstanceRequest) -> Result<InstanceEndpoint> {
        let (port, wt_port) = self.acquire_ports()?;
        // From here, any early return must hand the ports back to the pool.
        let result = (|| {
            let (cert_b64, key_b64, cert_hash_hex) = mint_wt_cert()?;
            let tokens = player_tokens_json(&req.players);
            let replay_dir = std::env::temp_dir().join(format!("match-{}", req.match_id));
            let mut cmd = tokio::process::Command::new(&self.server_bin);
            cmd.arg("--bind")
                .arg(format!("0.0.0.0:{port}"))
                .arg("--arena")
                .arg(&req.arena)
                .arg("--grace-secs")
                .arg(req.grace_secs.to_string())
                .arg("--match-secs")
                .arg(req.match_secs.to_string())
                .arg("--seed")
                .arg(req.seed.to_string())
                .arg("--replay-dir")
                .arg(&replay_dir)
                .arg("--wt-bind")
                .arg(format!("0.0.0.0:{wt_port}"))
                .env("WT_CERT_DER_B64", cert_b64)
                .env("WT_KEY_DER_B64", key_b64)
                .env("PLAYER_TOKENS", tokens)
                .env("MATCH_ID", &req.match_id)
                .env("REPORT_URL", &req.report_url)
                .env("REPORT_TOKEN", &req.report_token);
            if let Some(url) = &req.replay_upload_url {
                cmd.env("REPLAY_UPLOAD_URL", url);
            }
            let child = cmd
                .kill_on_drop(false) // instance self-exits at the deadline
                .spawn()
                .context("spawn game server")?;
            Ok::<_, anyhow::Error>((child, cert_hash_hex))
        })();
        let (child, cert_hash_hex) = match result {
            Ok(v) => v,
            Err(e) => {
                self.release_ports((port, wt_port));
                return Err(e);
            }
        };
        // Tokens/keys are secret: log only the team_uuids and the listen port.
        tracing::info!(
            match_id = %req.match_id,
            port,
            pid = child.id(),
            players = req.players.len(),
            "instance spawned"
        );
        // The instance owns its own lifetime from here; reap in background,
        // recycle its ports, and — on a clean exit — export the now-finalized
        // replay to the bucket so spectators can view it (post-match only).
        let game_ports = (port, wt_port);
        let free = self.free_ports.clone();
        let replay_dir = std::env::temp_dir().join(format!("match-{}", req.match_id));
        let bucket = self.replay_bucket.clone();
        let match_id = req.match_id.clone();
        let challenge_id = req.challenge_id.clone();
        tokio::spawn(async move {
            let mut child = child;
            let status = child.wait().await;
            crate::state::lock(&free).push_back(game_ports);
            if let Some(bucket) = bucket {
                let clean = status.map(|s| s.success()).unwrap_or(false);
                if clean {
                    export_replay(&replay_dir, &bucket, &challenge_id, &match_id).await;
                } else {
                    tracing::warn!(%match_id, "instance exited uncleanly; replay not exported");
                }
            }
        });
        Ok(InstanceEndpoint {
            host: self.public_host.clone(),
            port,
            cert_hash_hex: Some(cert_hash_hex.clone()),
            routed: false,
            wt: Some(WtInfo {
                port: wt_port,
                cert_hash_hex,
            }),
        })
    }
}

const CRD_API: &str = "rctf-instancer.osec.io/v1";
const EXPIRY_SLACK_SECS: u64 = 60;

/// Creates `ChallengeInstance` objects via the kube client — the same CRD the
/// rCTF `k8s-instancer.ts` provider targets. The resource is cluster-scoped,
/// so we go through `Api::all_with`.
pub struct K8sInstancer {
    client: kube::Client,
    resource: kube::api::ApiResource,
}

impl K8sInstancer {
    /// Mirrors the rCTF provider's env contract: API URL, bearer token, and a
    /// CA the server cert is pinned to. The udp-router front door is per-request
    /// (forwarded in the config), not a backend setting.
    pub fn from_env() -> Result<Self> {
        let api_url =
            std::env::var("K8S_INSTANCER_API_URL").context("K8S_INSTANCER_API_URL is unset")?;
        let auth_token = std::env::var("K8S_INSTANCER_AUTH_TOKEN")
            .context("K8S_INSTANCER_AUTH_TOKEN is unset")?;
        let ca_raw = std::env::var("K8S_INSTANCER_CA_CERTIFICATE")
            .context("K8S_INSTANCER_CA_CERTIFICATE is unset")?;
        let root_certs: Vec<Vec<u8>> = pem::parse_many(decode_ca(&ca_raw)?)
            .context("parse K8S_INSTANCER_CA_CERTIFICATE")?
            .iter()
            .map(|p| p.contents().to_vec())
            .collect();

        let mut config = kube::Config::new(
            api_url
                .parse()
                .context("K8S_INSTANCER_API_URL is not a valid URL")?,
        );
        config.root_cert = Some(root_certs);
        config.auth_info = kube::config::AuthInfo {
            token: Some(auth_token.into()),
            ..Default::default()
        };
        let client = kube::Client::try_from(config).context("build kube client")?;

        let gvk =
            kube::api::GroupVersionKind::gvk("rctf-instancer.osec.io", "v1", "ChallengeInstance");
        let resource = kube::api::ApiResource::from_gvk_with_plural(&gvk, "challengeinstances");

        Ok(Self { client, resource })
    }

    fn api(&self) -> kube::Api<kube::api::DynamicObject> {
        kube::Api::all_with(self.client.clone(), &self.resource)
    }

    /// Best-effort delete so a finished/voided match's pod is GC'd promptly
    /// rather than waiting for `expiresAt`.
    pub async fn destroy(&self, name: &str) {
        match self
            .api()
            .delete(name, &kube::api::DeleteParams::default())
            .await
        {
            Ok(_) => {}
            Err(kube::Error::Api(e)) if e.code == 404 => {}
            Err(e) => tracing::warn!(name, error = %e, "challengeinstance delete failed"),
        }
    }
}

impl Instancer for K8sInstancer {
    async fn create(&self, req: &InstanceRequest) -> Result<InstanceEndpoint> {
        let config = req
            .config
            .as_ref()
            .context("k8s instancer requires a forwarded pod config")?;
        // The udp-router players dial is part of the forwarded config (rCTF's
        // instancer schema storage), so it's swappable mid-event.
        let (host, port) = udprouter_from_config(config)?;
        let expires_at = expiry_rfc3339(req.grace_secs + req.match_secs + EXPIRY_SLACK_SECS)?;
        let (cert_b64, key_b64, cert_hash_hex) = mint_wt_cert()?;
        let name = challenge_instance_name(&req.challenge_id, &req.match_id);
        let body = build_challenge_instance(
            config,
            &req.instance_id,
            &req.match_id,
            &req.challenge_id,
            &req.players,
            &req.report_url,
            req.replay_upload_url.as_deref(),
            &cert_b64,
            &key_b64,
            &req.report_token,
            req.grace_secs,
            req.match_secs,
            &req.arena,
            req.seed,
            &expires_at,
        );
        let obj: kube::api::DynamicObject =
            serde_json::from_value(body).context("build ChallengeInstance object")?;

        // 409 = already exists; treat as idempotent like the TS provider.
        match self
            .api()
            .create(&kube::api::PostParams::default(), &obj)
            .await
        {
            Ok(_) => {}
            Err(kube::Error::Api(e)) if e.code == 409 => {}
            Err(e) => return Err(e).context("create challengeinstance"),
        }
        tracing::info!(
            match_id = %req.match_id,
            %name,
            instance_id = %req.instance_id,
            "challengeinstance created"
        );

        Ok(InstanceEndpoint {
            host,
            port,
            cert_hash_hex: Some(cert_hash_hex),
            routed: true,
            wt: None,
        })
    }
}

/// Build the ChallengeInstance object: copy the forwarded pods, tag each with
/// the routing instance-id label, and inject the instance-mode env (player
/// tokens, match id, report url/token) plus match-length args into the primary
/// game-server container. No `expose` — routing is the udp-router label only.
#[allow(clippy::too_many_arguments)]
pub fn build_challenge_instance(
    config: &serde_json::Value,
    instance_id: &str,
    match_id: &str,
    challenge_id: &str,
    players: &[(String, String, String)],
    report_url: &str,
    replay_upload_url: Option<&str>,
    cert_der_b64: &str,
    key_der_b64: &str,
    report_token: &str,
    grace_secs: u64,
    match_secs: u64,
    arena: &str,
    seed: u64,
    expires_at: &str,
) -> serde_json::Value {
    let mut pods = config
        .get("pods")
        .and_then(|p| p.as_array())
        .cloned()
        .unwrap_or_default();

    let tokens = player_tokens_json(players);
    let mut injected_env = vec![
        ("PLAYER_TOKENS", tokens.as_str()),
        ("MATCH_ID", match_id),
        ("REPORT_URL", report_url),
        ("REPORT_TOKEN", report_token),
        ("WT_CERT_DER_B64", cert_der_b64),
        ("WT_KEY_DER_B64", key_der_b64),
    ];
    if let Some(url) = replay_upload_url {
        injected_env.push(("REPLAY_UPLOAD_URL", url));
    }

    for pod in pods.iter_mut() {
        if let Some(obj) = pod.as_object_mut() {
            let labels = obj.entry("labels").or_insert_with(|| json!({}));
            if let Some(map) = labels.as_object_mut() {
                map.insert("udprouter.es3n1n.io/instance-id".into(), json!(instance_id));
            }
        }

        if let Some(containers) = pod
            .pointer_mut("/spec/containers")
            .and_then(|c| c.as_array_mut())
        {
            if let Some(container) = primary_container(containers) {
                if let Some(cobj) = container.as_object_mut() {
                    let env = cobj.entry("env").or_insert_with(|| json!([]));
                    if let Some(arr) = env.as_array_mut() {
                        for (k, v) in &injected_env {
                            arr.push(json!({"name": k, "value": v}));
                        }
                    }
                }
                if let Some(cobj) = container.as_object_mut() {
                    let args = cobj.entry("args").or_insert_with(|| json!([]));
                    if let Some(arr) = args.as_array_mut() {
                        arr.push(json!("--grace-secs"));
                        arr.push(json!(grace_secs.to_string()));
                        arr.push(json!("--match-secs"));
                        arr.push(json!(match_secs.to_string()));
                        arr.push(json!("--arena"));
                        arr.push(json!(arena));
                        arr.push(json!("--seed"));
                        arr.push(json!(seed.to_string()));
                    }
                }
            }
        }
    }

    json!({
        "apiVersion": CRD_API,
        "kind": "ChallengeInstance",
        "metadata": { "name": challenge_instance_name(challenge_id, match_id) },
        "spec": {
            "pods": pods,
            "teamId": match_id,
            "challengeId": k8s_name_segment(challenge_id),
            "expiresAt": expires_at,
        },
    })
}

/// The game-server container: prefer one named "app", else the first.
fn primary_container(containers: &mut [serde_json::Value]) -> Option<&mut serde_json::Value> {
    let idx = containers
        .iter()
        .position(|c| c.get("name").and_then(|n| n.as_str()) == Some("app"))
        .or(if containers.is_empty() { None } else { Some(0) })?;
    containers.get_mut(idx)
}

fn decode_ca(raw: &str) -> Result<Vec<u8>> {
    if raw.contains("-----BEGIN") {
        Ok(raw.as_bytes().to_vec())
    } else {
        base64::engine::general_purpose::STANDARD
            .decode(raw.trim())
            .context("base64-decode CA certificate")
    }
}

/// The udp-router front door (`host:port`) players dial — forwarded by rCTF in
/// the provider config, alongside `pods`.
fn udprouter_from_config(config: &serde_json::Value) -> Result<(String, u16)> {
    let addr = config
        .get("udprouterAddr")
        .and_then(|v| v.as_str())
        .context("forwarded config is missing `udprouterAddr` (host:port)")?;
    parse_hostport(addr)
}

fn parse_hostport(s: &str) -> Result<(String, u16)> {
    let (h, p) = s
        .rsplit_once(':')
        .with_context(|| format!("expected host:port, got {s:?}"))?;
    Ok((h.to_string(), p.parse().context("invalid port")?))
}

fn expiry_rfc3339(secs_from_now: u64) -> Result<String> {
    use time::format_description::well_known::Rfc3339;
    let t = time::OffsetDateTime::now_utc() + time::Duration::seconds(secs_from_now as i64);
    t.format(&Rfc3339).context("format expiresAt")
}

/// Runtime instancer selection. `async fn` in traits is not dyn-compatible, so
/// dispatch through an enum rather than `Arc<dyn Instancer>`.
pub enum GameInstancer {
    Local(LocalProcess),
    K8s(K8sInstancer),
}

impl GameInstancer {
    pub async fn create(&self, req: &InstanceRequest) -> Result<InstanceEndpoint> {
        match self {
            GameInstancer::Local(l) => l.create(req).await,
            GameInstancer::K8s(k) => k.create(req).await,
        }
    }

    pub async fn destroy(&self, name: &str) {
        if let GameInstancer::K8s(k) = self {
            k.destroy(name).await;
        }
    }
}

