    fn sample_config() -> serde_json::Value {
        json!({"pods": [{
            "name": "app",
            "ports": [{"port": 1337, "protocol": "UDP"}],
            "spec": {"containers": [{
                "name": "app",
                "image": "minions-server:latest",
                "args": ["--bind", "0.0.0.0:1337", "--replay-dir", "/srv/minions/replays"],
            }]},
        }]})
    }

    #[test]
    fn challenge_instance_labels_pods_and_injects_env() {
        let players = vec![(
            "team-1".to_string(),
            "Team One".to_string(),
            "deadbeef".to_string(),
        )];
        let body = build_challenge_instance(
            &sample_config(),
            "11223344556677881122334455667788",
            "m-abc",
            "minions",
            &players,
            "http://backend/api/report",
            Some("http://backend/api/replay/upload"),
            "cert-b64",
            "key-b64",
            "tok",
            30,
            300,
            "gru-lab-v3",
            0xfeedface,
            "2026-06-14T00:00:00Z",
        );

        assert_eq!(body["metadata"]["name"], "minions-m-abc");
        assert_eq!(body["spec"]["teamId"], "m-abc");
        assert_eq!(body["spec"]["challengeId"], "minions");
        assert_eq!(body["spec"]["expiresAt"], "2026-06-14T00:00:00Z");
        // routing is the label only — never k8s Services / expose
        assert!(body["spec"].get("expose").is_none());

        let pod = &body["spec"]["pods"][0];
        assert_eq!(
            pod["labels"]["udprouter.es3n1n.io/instance-id"],
            "11223344556677881122334455667788"
        );

        let container = &pod["spec"]["containers"][0];
        let env = container["env"].as_array().unwrap();
        let names: Vec<&str> = env.iter().map(|e| e["name"].as_str().unwrap()).collect();
        for want in [
            "PLAYER_TOKENS",
            "MATCH_ID",
            "REPORT_URL",
            "REPORT_TOKEN",
            "REPLAY_UPLOAD_URL",
            "WT_CERT_DER_B64",
            "WT_KEY_DER_B64",
        ] {
            assert!(names.contains(&want), "missing env {want}");
        }
        let tokens = env.iter().find(|e| e["name"] == "PLAYER_TOKENS").unwrap();
        assert!(tokens["value"].as_str().unwrap().contains("team-1"));

        let args: Vec<&str> = container["args"]
            .as_array()
            .unwrap()
            .iter()
            .map(|a| a.as_str().unwrap())
            .collect();
        assert!(args
            .windows(2)
            .any(|w| w[0] == "--grace-secs" && w[1] == "30"));
        assert!(args
            .windows(2)
            .any(|w| w[0] == "--match-secs" && w[1] == "300"));
        assert!(args
            .windows(2)
            .any(|w| w[0] == "--arena" && w[1] == "gru-lab-v3"));
        assert!(args
            .windows(2)
            .any(|w| w[0] == "--seed" && w[1] == "4277009102"));
        // original args preserved
        assert!(args.contains(&"--bind"));
    }

    #[test]
    fn challenge_instance_creates_labels_map_when_absent() {
        let cfg = json!({"pods": [{"name": "app", "ports": [], "spec": {"containers": []}}]});
        let body = build_challenge_instance(
            &cfg,
            "abcd",
            "m1",
            "minions",
            &[],
            "u",
            None,
            "cert-b64",
            "key-b64",
            "t",
            30,
            300,
            "arena",
            7,
            "2026-06-14T00:00:00Z",
        );
        assert_eq!(
            body["spec"]["pods"][0]["labels"]["udprouter.es3n1n.io/instance-id"],
            "abcd"
        );
    }

    #[test]
    fn challenge_instance_name_sanitizes_rctf_ids_for_kubernetes() {
        assert_eq!(
            challenge_instance_name("game_minions-in-16k", "m-abc"),
            "game-minions-in-16k-m-abc"
        );
        assert_eq!(
            challenge_instance_name("_Bad.ID_", "_Match_"),
            "bad-id-match"
        );
        assert_eq!(challenge_instance_name("___", "___"), "minions-instance");
    }

    #[test]
    fn challenge_instance_spec_uses_kubernetes_safe_challenge_id() {
        let body = build_challenge_instance(
            &sample_config(),
            "abcd",
            "m-7d3dee2f91f4",
            "game_minions-in-16k",
            &[],
            "u",
            None,
            "cert-b64",
            "key-b64",
            "t",
            30,
            300,
            "arena",
            7,
            "2026-06-14T00:00:00Z",
        );

        assert_eq!(
            body["metadata"]["name"],
            "game-minions-in-16k-m-7d3dee2f91f4"
        );
        assert_eq!(body["spec"]["challengeId"], "game-minions-in-16k");
        assert_eq!(body["spec"]["teamId"], "m-7d3dee2f91f4");
    }

    #[test]
    fn connection_routed_emits_instance_id_and_no_wasm() {
        let ep = InstanceEndpoint {
            host: "udprouter.es3n1n.io".into(),
            port: 1337,
            cert_hash_hex: Some("cafebabe".into()),
            routed: true,
            wt: None,
        };
        let lines = build_connection(&ep, "abcd1234", "k1", "http://backend");
        assert!(lines.iter().any(|l| l.contains("--instance-id abcd1234")));
        assert!(lines.iter().any(|l| l.contains("--cert-hash cafebabe")));
        assert!(lines.iter().all(|l| !l.contains("/wasm")));
    }

    #[test]
    fn connection_direct_has_wasm_and_no_instance_id() {
        let ep = InstanceEndpoint {
            host: "127.0.0.1".into(),
            port: 4500,
            cert_hash_hex: None,
            routed: false,
            wt: Some(WtInfo {
                port: 4501,
                cert_hash_hex: "hh".into(),
            }),
        };
        let lines = build_connection(&ep, "abcd1234", "k1", "http://backend");
        assert!(lines.iter().all(|l| !l.contains("--instance-id")));
        assert!(lines.iter().any(|l| l.contains("/wasm")));
        assert!(lines.iter().any(|l| l.contains("certhash=hh")));
    }

    #[test]
    fn hostport_splits_on_last_colon() {
        assert_eq!(
            parse_hostport("udprouter.es3n1n.io:1337").unwrap(),
            ("udprouter.es3n1n.io".to_string(), 1337)
        );
    }

    #[test]
    fn udprouter_addr_read_from_config() {
        let cfg = json!({"pods": [], "udprouterAddr": "udprouter.es3n1n.io:1337"});
        assert_eq!(
            udprouter_from_config(&cfg).unwrap(),
            ("udprouter.es3n1n.io".to_string(), 1337)
        );
        assert!(udprouter_from_config(&json!({"pods": []})).is_err());
    }
